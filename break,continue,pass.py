print("Break Example") #break
for i in range(1,6):
    if i==4:
        break
    print(i)

print("\nContinue Example") #continue
for i in range(1,6):
    if i==4:
        continue
    print(i)

print("\nPass Example") #pass
for i in range(1,6):
    if i==3:
        pass
    print(i)
    
